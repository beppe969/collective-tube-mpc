@dataclass
class Plant:
    name:str
    A:np.ndarray
    B:np.ndarray
    K:np.ndarray
    H:int
    Q:np.ndarray
    R:float
    xmax:np.ndarray
    umax:float
    transition:np.ndarray
    L:np.ndarray
    means:np.ndarray
    alpha0:float=0.
    gamma:float=1.
    heavy_scale:float=1.
    @property
    def AK(self): return self.A+self.B@self.K
    @property
    def ng(self): return len(self.L)
    @property
    def P(self): return solve_discrete_lyapunov(self.AK.T,self.Q+self.R*(self.K.T@self.K))


